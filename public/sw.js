// Service worker — app-shell precache + runtime caching.
//
// NOTE: this file is served to clients verbatim. Keep comments to the
// invariants a maintainer needs; rationale and history live in the internal
// notes, not here.
//
// Routing:
//   - /api/*  network-only. Auth and sync must never see a stale response.
//   - hashed build assets, root binaries  cache-first (immutable).
//   - HTML / navigations  network-first with cache fallback.
//
// INVARIANT: cache lifetime is governed by the build manifest, pruned on
// activate — NEVER by renaming caches. Version-suffixed cache names wipe the
// shell on every bump and break offline until each route is re-visited.
const SW_VERSION  = "0.6.0-offline-shell";
const STATIC_CACHE = "forge-static-v1";
const HTML_CACHE   = "forge-shell-v1";

// Build-time precache manifest (generated by scripts/generate-sw-precache.mjs
// on postbuild; gitignored). Absent in dev — the guard leaves PRECACHE null
// and the worker behaves like the runtime-only version. Browsers byte-check
// imported scripts on SW update checks, so each deploy's new manifest content
// triggers the update cycle without touching this file.
let PRECACHE = null;
try {
  importScripts("/sw-precache.js");
  if (self.__FORGE_PRECACHE && Array.isArray(self.__FORGE_PRECACHE.assets)) {
    PRECACHE = self.__FORGE_PRECACHE;
  }
} catch {
  // dev / manifest missing — runtime caching only.
}

// Precache list — must stay tiny. Anything else is added at runtime.
// The pre-rebrand icon paths were retired 2026-08-31; the migration window
// has closed and nothing referenced them.
const PRECACHE_URLS = [
  "/manifest.json",
  "/heatwayve/heatwayve-glass-192.png",
  "/heatwayve/heatwayve-glass-512.png",
  "/apple-touch-icon.png",
];

// Update UX. INVARIANT: no unconditional skipWaiting. Activating a new
// build under a live tab prunes the old build's hashed bundles (see
// activate) — a page that then lazy-loads an old chunk 404s and strands.
// Instead the new worker WAITS; the registrar tells it to take over only
// at a safe moment (tab hidden, no live session draft), and rides the
// controllerchange with an immediate reload so page and caches always
// swap together. First-ever install never waits (no prior active worker),
// so first-load control via clients.claim() is unchanged.
self.addEventListener("message", (event) => {
  if (event.data && event.data.type === "SKIP_WAITING") self.skipWaiting();
});

self.addEventListener("install", (event) => {

  // ── Static routing (Safari 27+ / spec'd addRoutes) ────────────────────
  // Routes the browser applies WITHOUT waking this worker. Scope is
  // deliberately limited to rules that are semantics-identical to the
  // fetch router below:
  //   - /api/*  → network. The router already early-returns for /api (auth
  //     + sync must always see fresh server state), so today the worker
  //     wakes only to decline. This removes the wake from every sync call.
  //   - The tiny PRECACHE set → cache (miss falls back to network per
  //     spec). These are install-time cached, so hits are guaranteed in
  //     steady state; on the rare miss the only delta vs cacheFirst is no
  //     re-population, acceptable for four stable files.
  //   - THIS build's manifest assets → cache, as EXACT paths. NEVER the
  //     wholesale /_next/static/* pattern: a "cache" route never runs the
  //     fetch handler and so never populates, so mid-rollout the new build's
  //     hashes would resolve against a cache that has never seen them and
  //     offline would break. Exact paths fall through to the fetch router
  //     instead, where cacheFirst populates them.
  // Feature-guarded: browsers without addRoutes just use the fetch router
  // for everything, as today.
  if ("addRoutes" in event) {
    try {
      const manifestAssetRoutes = (PRECACHE ? PRECACHE.assets : []).map((path) => (
        { condition: { urlPattern: { pathname: path } }, source: "cache" }
      ));
      event.addRoutes([
        { condition: { urlPattern: { pathname: "/api/*" } }, source: "network" },
        { condition: { urlPattern: { pathname: "/manifest.json" } }, source: "cache" },
        { condition: { urlPattern: { pathname: "/heatwayve/heatwayve-glass-192.png" } }, source: "cache" },
        { condition: { urlPattern: { pathname: "/heatwayve/heatwayve-glass-512.png" } }, source: "cache" },
        { condition: { urlPattern: { pathname: "/apple-touch-icon.png" } }, source: "cache" },
        ...manifestAssetRoutes,
      ]).catch((err) => console.warn("[sw] addRoutes rejected:", err));
    } catch (err) {
      // Malformed-rule errors must never block install.
      console.warn("[sw] addRoutes failed:", err);
    }
  }

  event.waitUntil((async () => {
    // Tiny always-needed set (icons/manifest) — as before.
    const statics = await caches.open(STATIC_CACHE);
    await statics.addAll(PRECACHE_URLS).catch((err) => {
      // Don't block install if a precache asset 404s on this deploy —
      // runtime caching will still pick it up on first request.
      console.warn("[sw] precache failed:", err);
    });

    if (!PRECACHE) return; // dev / no manifest — runtime-only behaviour

    // App-shell precache: this build's hashed bundles + the
    // shell routes' HTML, so offline cold-start works on routes the user
    // never visited. Per-entry tolerance — one 404 must not kill install.
    await Promise.all(PRECACHE.assets.map(async (path) => {
      if (await statics.match(path)) return; // hashed = immutable, keep
      try {
        const res = await fetch(path);
        if (res.ok) await statics.put(path, res);
      } catch { /* offline install — runtime picks it up later */ }
    }));

    const shell = await caches.open(HTML_CACHE);
    await Promise.all(PRECACHE.shellRoutes.map(async (route) => {
      try {
        // no-cache: the shell must be THIS deploy's HTML (it references
        // this build's hashed bundles), not a stale browser-cache copy.
        const res = await fetch(route, { cache: "no-cache" });
        if (res.ok) await shell.put(route, res);
      } catch { /* tolerate — networkFirst still populates on visit */ }
    }));
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    // One-time migration: drop the old version-suffixed caches.
    const keys = await caches.keys();
    const stale = keys.filter((k) => k.startsWith("forge-") && k !== STATIC_CACHE && k !== HTML_CACHE);
    await Promise.all(stale.map((k) => caches.delete(k)));

    // Prune, don't wipe: remove /_next/static entries that
    // aren't in the CURRENT build's manifest (old hashed bundles), leaving
    // icons/fonts and everything still referenced. Offline keeps working
    // across deploys because the new build was precached at install, before
    // this delete runs.
    if (PRECACHE) {
      const current = new Set(PRECACHE.assets);
      const statics = await caches.open(STATIC_CACHE);
      for (const req of await statics.keys()) {
        const path = new URL(req.url).pathname;
        if (path.startsWith("/_next/static/") && !current.has(path)) {
          await statics.delete(req);
        }
      }
    }
    await self.clients.claim();
  })());
});

// ─── Strategy: cache-first ─────────────────────────────────────────────────
// Use for immutable assets (content-hashed bundles, icons). Returns cache
// hit immediately; populates cache on miss; falls through to network error
// if both cache and network fail.
async function cacheFirst(req, cacheName) {
  const cache  = await caches.open(cacheName);
  const cached = await cache.match(req);
  if (cached) return cached;
  const res = await fetch(req);
  if (res.ok) {
    // Clone before consuming — Response bodies are single-use.
    cache.put(req, res.clone()).catch(() => { /* quota errors are non-fatal */ });
  }
  return res;
}

// ─── Strategy: network-first with cache fallback ───────────────────────────
// Use for HTML / navigation. Online users always get the freshest shell;
// offline users get the last-cached version so the PWA still opens at the
// gym when wifi is flaky.
async function networkFirst(req, cacheName) {
  const cache = await caches.open(cacheName);
  try {
    const res = await fetch(req);
    if (res.ok) {
      cache.put(req, res.clone()).catch(() => { /* quota errors are non-fatal */ });
    }
    return res;
  } catch (err) {
    const cached = await cache.match(req);
    if (cached) return cached;
    throw err;
  }
}

// ─── Fetch router ──────────────────────────────────────────────────────────
self.addEventListener("fetch", (event) => {
  const req = event.request;

  // Only handle GET — POST/PUT/DELETE go straight to network.
  if (req.method !== "GET") return;

  const url = new URL(req.url);

  // Only handle same-origin — cross-origin (Vercel blob, analytics, etc.)
  // is left to the browser cache.
  if (url.origin !== self.location.origin) return;

  // API routes: never cache. Auth + sync must always see fresh server state.
  if (url.pathname.startsWith("/api/")) return;

  // Content-hashed Next bundles: cache-first, immutable.
  if (url.pathname.startsWith("/_next/static/")) {
    event.respondWith(cacheFirst(req, STATIC_CACHE));
    return;
  }

  // Root-level static binaries (icons, favicon, fonts). Path-based test
  // covers PWA assets that aren't fingerprinted.
  if (/\.(png|jpe?g|svg|webp|gif|ico|woff2?|otf|ttf)$/i.test(url.pathname)) {
    event.respondWith(cacheFirst(req, STATIC_CACHE));
    return;
  }

  // Manifest: cache-first so PWA installability survives offline.
  if (url.pathname === "/manifest.json") {
    event.respondWith(cacheFirst(req, STATIC_CACHE));
    return;
  }

  // RSC payloads (client-side navigations): network-first; when
  // offline, match ignoring the `_rsc` search param — its value varies per
  // build but the pathname identifies the route. No cached payload → the
  // fetch rejects and Next falls back to a hard navigation, which lands in
  // the navigation branch below and gets the cached shell.
  if (url.searchParams.has("_rsc")) {
    event.respondWith((async () => {
      const cache = await caches.open(HTML_CACHE);
      try {
        const res = await fetch(req);
        if (res.ok) cache.put(req, res.clone()).catch(() => {});
        return res;
      } catch (err) {
        const cached = await cache.match(req, { ignoreSearch: true });
        if (cached) return cached;
        throw err;
      }
    })());
    return;
  }

  // HTML / navigation: network-first, with a deeper offline fallback chain
  // Exact URL → same-pathname ignoring search → precached "/"
  // as a best-effort last resort (the client router recovers the route).
  if (req.mode === "navigate" || (req.headers.get("accept") || "").includes("text/html")) {
    event.respondWith((async () => {
      try {
        return await networkFirst(req, HTML_CACHE);
      } catch (err) {
        const cache = await caches.open(HTML_CACHE);
        const byPath = await cache.match(req, { ignoreSearch: true });
        if (byPath) return byPath;
        const root = await cache.match("/");
        if (root) return root;
        throw err;
      }
    })());
    return;
  }

  // Anything else (Next data fetches, server actions, etc.) — pass through.
});
